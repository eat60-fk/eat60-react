create or replace function public.validate_coupon(p_code text, p_subtotal int)
returns jsonb language plpgsql security definer set search_path = public as $$
declare c coupons%rowtype; v_used int; v_discount int;
begin
  if auth.uid() is null then raise exception 'Please log in first'; end if;
  if coalesce(trim(p_code),'') = '' then return jsonb_build_object('valid',false,'message','Enter a coupon code.'); end if;
  select * into c from coupons where code = upper(trim(p_code)) and is_active;
  if not found then return jsonb_build_object('valid',false,'message','This coupon is not available.'); end if;
  if c.starts_at is not null and now() < c.starts_at then return jsonb_build_object('valid',false,'message','This coupon is not active yet.'); end if;
  if c.expires_at is not null and now() >= c.expires_at then return jsonb_build_object('valid',false,'message','This coupon has expired.'); end if;
  if c.usage_limit is not null and c.used_count >= c.usage_limit then return jsonb_build_object('valid',false,'message','This coupon has reached its redemption limit.'); end if;
  if coalesce(p_subtotal,0) < c.minimum_order then return jsonb_build_object('valid',false,'message',format('Add items worth ₹%s to use this coupon.',c.minimum_order)); end if;
  select count(*) into v_used from coupon_redemptions where coupon_id=c.id and user_id=auth.uid();
  if v_used >= c.per_user_limit then return jsonb_build_object('valid',false,'message','You have used this coupon the maximum number of times.'); end if;
  v_discount := case when c.discount_type='percent' then floor(p_subtotal*c.discount_value/100.0)::int else c.discount_value end;
  v_discount := least(greatest(0,p_subtotal),coalesce(least(v_discount,c.maximum_discount),v_discount));
  return jsonb_build_object('valid',true,'code',c.code,'description',c.description,'discount_amount',v_discount);
end $$;

