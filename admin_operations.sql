create or replace function public.place_order_with_coupon(
  p_items jsonb,
  p_use_coins boolean,
  p_address text,
  p_phone text,
  p_coupon_code text default null,
  p_customer_name text default null,
  p_distance_km numeric default null
)
returns bigint language plpgsql security definer set search_path = public as $$
declare
  s settings%rowtype; p profiles%rowtype; c coupons%rowtype;
  r record; e record; x record; v record; v_oid bigint;
  v_sub int:=0; v_unit int; v_extra_price int; v_coin_discount int:=0;
  v_coins_used int:=0; v_coupon_discount int:=0; v_total int; v_extra_details jsonb;
  v_delivery_fee int; v_delivery_fee_before_discount int; v_gst_amount int;
  v_user_uses int; v_coupon_code text;
begin
  if auth.uid() is null then raise exception 'Please log in first'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items)=0 then raise exception 'Your cart is empty'; end if;
  select * into s from settings where id=1;
  if not coalesce(s.store_online,true) then raise exception '%',coalesce(s.offline_message,'Ordering is offline right now.'); end if;
  select * into p from profiles where id=auth.uid() for update;
  if coalesce(trim(p_address),'')='' then raise exception 'Delivery address is required'; end if;
  if coalesce(trim(p_phone),'')='' then raise exception 'Phone number is required'; end if;
  if coalesce(trim(p_customer_name),trim(p.name),'')='' then raise exception 'Customer name is required'; end if;
  if p_distance_km is not null and (p_distance_km<0 or p_distance_km>s.max_delivery_km) then
    raise exception 'Delivery is available only within % km',s.max_delivery_km;
  end if;

  insert into orders(
    user_id,address,phone,customer_name,delivery_fee,delivery_fee_before_discount,delivery_distance_km,order_stage
  )
  values(
    auth.uid(),trim(p_address),nullif(trim(p_phone),''),coalesce(nullif(trim(p_customer_name),''),p.name),
    0,0,p_distance_km,'pending'
  ) returning id into v_oid;

  for r in select value from jsonb_array_elements(p_items) loop
    select vr.id as variant_id,vr.item_id,
      case when vr.id=s.offer_variant_id and s.offer_date=today_ist()
        and (s.offer_ends_at is null or s.offer_ends_at>now()) then s.offer_price else vr.price end as price,
      vr.label,i.name,i.brand_id,i.is_available,b.is_open
    into v from item_variants vr join menu_items i on i.id=vr.item_id join brands b on b.id=i.brand_id
    where vr.id=(r.value->>'variant_id')::bigint;
    if not found then raise exception 'A selected menu size no longer exists'; end if;
    if not v.is_available or not v.is_open then raise exception '% is not available right now',v.name; end if;
    v_extra_price:=0; v_extra_details:='[]'::jsonb;
    for e in select value from jsonb_array_elements(coalesce(r.value->'extras','[]'::jsonb)) loop
      select id,name,price into x from item_extras
      where id=(e.value->>'id')::bigint and item_id=v.item_id and is_available;
      if not found then raise exception 'A selected extra is no longer available'; end if;
      v_extra_price:=v_extra_price+x.price;
      v_extra_details:=v_extra_details||jsonb_build_array(jsonb_build_object('id',x.id,'name',x.name,'price',x.price));
    end loop;
    v_unit:=v.price+v_extra_price;
    insert into order_items(order_id,menu_item_id,brand_id,item_name,qty,unit_price,extra_details)
    values(v_oid,v.item_id,v.brand_id,v.name||' ('||v.label||')',greatest(1,least(20,coalesce((r.value->>'qty')::int,1))),v_unit,v_extra_details);
    v_sub:=v_sub+v_unit*greatest(1,least(20,coalesce((r.value->>'qty')::int,1)));
  end loop;
  if v_sub<s.min_order then raise exception 'Minimum order is ₹%',s.min_order; end if;

  v_delivery_fee_before_discount:=coalesce(s.delivery_fee,0)+ceil(
    greatest(0,coalesce(p_distance_km,s.min_delivery_km)-s.min_delivery_km)*coalesce(s.delivery_per_km,0)
  )::int;
  v_delivery_fee:=case
    when coalesce(s.delivery_free,false)
      or (coalesce(s.free_delivery_minimum,0)>0 and v_sub>=s.free_delivery_minimum) then 0
    else v_delivery_fee_before_discount
  end;
  v_gst_amount:=round(v_sub*5.0/105.0)::int;

  update orders set delivery_fee=v_delivery_fee,
    delivery_fee_before_discount=v_delivery_fee_before_discount,gst_amount=v_gst_amount where id=v_oid;

  v_coupon_code:=nullif(upper(trim(coalesce(p_coupon_code,''))),'');
  if v_coupon_code is not null then
    select * into c from coupons where code=v_coupon_code for update;
    if not found or not c.is_active then raise exception 'This coupon is not available'; end if;
    if c.starts_at is not null and now()<c.starts_at then raise exception 'This coupon is not active yet'; end if;
    if c.expires_at is not null and now()>=c.expires_at then raise exception 'This coupon has expired'; end if;
    if c.usage_limit is not null and c.used_count>=c.usage_limit then raise exception 'This coupon has reached its redemption limit'; end if;
    if v_sub<c.minimum_order then raise exception 'Coupon requires a minimum order of ₹%',c.minimum_order; end if;
    select count(*) into v_user_uses from coupon_redemptions where coupon_id=c.id and user_id=auth.uid();
    if v_user_uses>=c.per_user_limit then raise exception 'You have used this coupon the maximum number of times'; end if;
    v_coupon_discount:=case when c.discount_type='percent' then floor(v_sub*c.discount_value/100.0)::int else c.discount_value end;
    v_coupon_discount:=least(v_sub,coalesce(least(v_coupon_discount,c.maximum_discount),v_coupon_discount));
  end if;

  if coalesce(p_use_coins,false) then
    v_coin_discount:=least(p.coins/100,floor(greatest(0,v_sub-v_coupon_discount)*s.max_coin_pct/100.0)::int);
    v_coins_used:=v_coin_discount*100;
    if v_coins_used>0 then update profiles set coins=coins-v_coins_used where id=auth.uid(); end if;
  end if;
  v_total:=greatest(0,v_sub+v_delivery_fee-v_coupon_discount-v_coin_discount);
  update orders set subtotal=v_sub,coupon_code=v_coupon_code,coupon_discount=v_coupon_discount,
    coin_discount=v_coin_discount,coins_used=v_coins_used,total=v_total where id=v_oid;
  if v_coupon_code is not null then
    update coupons set used_count=used_count+1 where id=c.id;
    insert into coupon_redemptions(coupon_id,user_id,order_id,discount_amount)
    values(c.id,auth.uid(),v_oid,v_coupon_discount);
  end if;
  return v_oid;
end $$;

create or replace function public.admin_update_order(
  p_id bigint,p_stage text,p_reason text default null,p_payment_type text default null
)
returns void language plpgsql security definer set search_path = public as $$
declare o orders%rowtype; s settings%rowtype; p profiles%rowtype; d date; n int; v_legacy_status text;
begin
  if not is_admin() then raise exception 'Admins only'; end if;
  select * into o from orders where id=p_id for update;
  if not found then raise exception 'Order not found'; end if;
  if o.order_stage in ('delivered','rejected','cancelled') then raise exception 'Order is already closed'; end if;
  if p_stage='rejected' then
    if o.order_stage<>'pending' then raise exception 'Only pending orders can be rejected'; end if;
    if coalesce(trim(p_reason),'')='' then raise exception 'Enter a reason for rejecting this order'; end if;
  elsif p_stage='accepted' then
    if o.order_stage<>'pending' then raise exception 'Only pending orders can be accepted'; end if;
  elsif p_stage='preparing' then
    if o.order_stage<>'accepted' then raise exception 'Accept the order before preparing it'; end if;
  elsif p_stage='ready' then
    if o.order_stage<>'preparing' then raise exception 'Only preparing orders can be marked ready'; end if;
  elsif p_stage='out_for_delivery' then
    if o.order_stage<>'ready' then raise exception 'Mark the order ready before dispatch'; end if;
  elsif p_stage='payment_received' then
    if o.order_stage<>'out_for_delivery' then raise exception 'Record payment after dispatch'; end if;
    if p_payment_type not in ('cash','upi','card','online','other') then raise exception 'Choose a payment type'; end if;
  elsif p_stage='delivered' then
    if o.order_stage<>'payment_received' then raise exception 'Record payment before marking delivered'; end if;
  elsif p_stage='cancelled' then
    if o.order_stage not in ('pending','accepted','preparing','ready') then raise exception 'This order can no longer be cancelled'; end if;
  else raise exception 'Unsupported order action';
  end if;

  v_legacy_status:=case when p_stage in ('accepted','preparing','ready') then 'preparing'
    when p_stage in ('out_for_delivery','payment_received') then 'out_for_delivery'
    when p_stage in ('delivered') then 'delivered'
    when p_stage in ('rejected','cancelled') then 'cancelled'
    else 'placed' end;
  update orders set order_stage=p_stage,status=v_legacy_status::order_status,
    accepted_at=case when p_stage='accepted' then now() else accepted_at end,
    ready_at=case when p_stage='ready' then now() else ready_at end,
    payment_received_at=case when p_stage='payment_received' then now() else payment_received_at end,
    payment_type=case when p_stage='payment_received' then p_payment_type else payment_type end,
    delivered_at=case when p_stage='delivered' then now() else delivered_at end,
    dispatched_at=case when p_stage='out_for_delivery' then now() else dispatched_at end,
    rejection_reason=case when p_stage='rejected' then trim(p_reason) when p_stage='cancelled' then nullif(trim(p_reason),'') else rejection_reason end
  where id=p_id;

  if p_stage in ('rejected','cancelled') and o.coins_used>0 then
    update profiles set coins=coins+o.coins_used where id=o.user_id;
  end if;
  if p_stage in ('rejected','cancelled') and o.coupon_code is not null then
    update coupons set used_count=greatest(0,used_count-1) where code=o.coupon_code;
    delete from coupon_redemptions where order_id=o.id;
  end if;
  if p_stage='delivered' then
    select * into s from settings where id=1;
    select * into p from profiles where id=o.user_id for update;
    d:=today_ist();
    if p.last_order_date is distinct from d then
      if p.last_order_date is null or d-p.last_order_date>s.streak_break_days then n:=1;
      else n:=p.streak+1; end if;
      update profiles set streak=n,longest_streak=greatest(longest_streak,n),last_order_date=d where id=o.user_id;
      insert into user_rewards(user_id,milestone,gift)
      select o.user_id,milestone,gift from streak_rewards where is_active and milestone=n on conflict do nothing;
    end if;
  end if;
end $$;

create or replace function public.auto_reject_expired_orders()
returns int language plpgsql security definer set search_path = public as $$
declare o orders%rowtype; v_count int:=0;
begin
  for o in select * from orders where order_stage='pending' and created_at<=now()-interval '5 minutes' for update skip locked loop
    update orders set order_stage='rejected',status='cancelled',rejection_reason='No response within 5 minutes'
    where id=o.id and order_stage='pending';
    if o.coins_used>0 then update profiles set coins=coins+o.coins_used where id=o.user_id; end if;
    if o.coupon_code is not null then
      update coupons set used_count=greatest(0,used_count-1) where code=o.coupon_code;
      delete from coupon_redemptions where order_id=o.id;
    end if;
    v_count:=v_count+1;
  end loop;
  return v_count;
end $$;

create or replace function public.admin_delete_outlet(p_id text)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not is_admin() then raise exception 'Admins only'; end if;
  if not exists(select 1 from brands where id=p_id) then raise exception 'Outlet not found'; end if;
  update settings set offer_variant_id=null,offer_price=null,offer_date=null,offer_ends_at=null
  where offer_variant_id in (select v.id from item_variants v join menu_items i on i.id=v.item_id where i.brand_id=p_id);
  delete from menu_items where brand_id=p_id;
  delete from brands where id=p_id;
end $$;

